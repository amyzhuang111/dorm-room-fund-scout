cells[1][1]='approve';cells[1][2]='Test reviewer';cells[1][3]=reviewed;
const approved=approveCsv(batch,encodeCsv(cells),reviewed);
assert.equal(approved.rows.length,1);
cells[1][4]='Another Person';
