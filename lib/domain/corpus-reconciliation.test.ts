import assert from 'node:assert/strict';
import {getDb} from '../db/client';
import {loadCorpusRows,filterCorpus,paginateCorpus,corpusToCsv} from './corpus-explorer';
import {loadPeopleCorpus,filterPeopleCorpus,peopleCorpusToCsv} from './people-corpus';
import {loadCorpusTotals} from './corpus-totals';
const db=getDb();
const count=(table:string)=>(db.prepare(`SELECT COUNT(*) n FROM ${table}`).get() as {n:number}).n;
const projects=loadCorpusRows();assert.equal(projects.length,count('projects'));assert.equal(new Set(projects.map(p=>p.id)).size,projects.length);
assert.equal(paginateCorpus({}).total,projects.length);
const scout=filterCorpus({scope:'scout'});assert.equal(scout.length,(db.prepare("SELECT COUNT(*) n FROM projects WHERE kind='company' AND is_investable_candidate=1").get() as {n:number}).n);
assert.ok(projects.length>scout.length);
const reviewed=filterCorpus({scope:'review'});assert.ok(reviewed.length>0);assert.ok(reviewed.every(p=>p.scoutingStatus==='Needs review'));
assert.ok(filterCorpus({q:'MUMU FurnCycle'}).length);
const people=loadPeopleCorpus();assert.equal(people.length,count('people'));assert.equal(new Set(people.map(p=>p.id)).size,people.length);
const matches=filterPeopleCorpus({q:'Shirin Ghorbani',campus:'univ_cornell',year:'2028'});assert.equal(matches.length,1);assert.equal(matches[0].yearChecked,true);
assert.ok(filterPeopleCorpus({year:'unknown'}).every(p=>p.graduationYear===null));
assert.equal(loadCorpusTotals().projectsTotal,projects.length);assert.equal(loadCorpusTotals().peopleTotal,people.length);assert.equal(loadCorpusTotals().investableCompanies,scout.length);
assert.match(peopleCorpusToCsv(matches),/elab-welcomes-32-student-startups/);
assert.match(corpusToCsv(projects.slice(0,1)),/source_urls/);
assert.match(peopleCorpusToCsv([{...matches[0],name:'=HYPERLINK("bad")'}]),/'=HYPERLINK/);
