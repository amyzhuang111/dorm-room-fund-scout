import assert from 'node:assert/strict';
import {getDb} from '../db/client';
import {loadPeopleCorpus,filterPeopleCorpus,peopleCorpusToCsv} from './people-corpus';
const db=getDb();const people=loadPeopleCorpus();
assert.equal(people.length,(db.prepare('SELECT COUNT(*) n FROM people').get() as {n:number}).n);
const verified=filterPeopleCorpus({review:'verified'});const unresolved=filterPeopleCorpus({review:'unresolved'});
assert.equal(verified.length+unresolved.length,people.length);
assert.ok(verified.every(p=>p.yearChecked&&p.graduationYear!=null&&p.yearSourceUrl&&p.educationObservations.some(o=>o.graduationYear===p.graduationYear)));
assert.ok(unresolved.every(p=>!p.yearChecked));
const byName=(name:string)=>{const p=people.find(p=>p.name===name);assert.ok(p,name);return p;};
assert.equal(byName('Octavius Kim').graduationYear,2023);
assert.equal(byName('Nathaneo Johnson').graduationYear,2026);
assert.equal(byName('Nick Lawton').graduationYear,2024);
assert.equal(byName('Jacob Bulbulia').graduationYear,2025);
assert.match(byName('Jacob Bulbulia').yearEvidence||'',/not proof of graduation/);
assert.equal(byName('Joshua Baek').yearChecked,false,'A confirmed historical observation must not hide a conflicting current report');
assert.equal(byName('Michael Wong').yearReviewStatus,'conflict');
assert.equal(byName('Utkarsh Saxena').previousYear,2012);
assert.equal(byName('Utkarsh Saxena').yearSourceUrl,null);
assert.deepEqual([...new Set(byName('Josh Aviv').educationObservations.map(o=>o.graduationYear))].sort(),[2015,2017]);
const selected=filterPeopleCorpus({review:'verified',q:'Nick Lawton',year:'2024'});assert.equal(selected.length,1);
const csv=peopleCorpusToCsv(selected);assert.match(csv,/class_year_review_date/);assert.match(csv,/2026-11-04/);assert.match(csv,/business.wisc.edu/);assert.match(csv,/class_year_observations/);
assert.match(peopleCorpusToCsv([{...selected[0],name:'=HYPERLINK("bad")'}]),/'=HYPERLINK/);
console.log(JSON.stringify({people:people.length,verified:verified.length,unresolved:unresolved.length,storedYears:people.filter(p=>p.graduationYear!=null).length}));
