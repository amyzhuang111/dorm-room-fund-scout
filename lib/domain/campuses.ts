export function campusById(id: string): CampusConfig | undefined {
  return CAMPUSES.find((c) => c.id === id);
}

export function shortCampusLabel(id: string, fallback?: string): string {
  return campusById(id)?.shortLabel ?? fallback ?? id;
}

export function shortCampusName(name: string): string {
  return CAMPUSES.find((c) => c.name === name)?.shortLabel ?? name;
}

/** A–Z for the label a person actually reads. No campus is pinned ahead of that order. */
export function compareCampusLabels(a: string, b: string): number {
  return a.localeCompare(b, "en", { sensitivity: "base" });
}

export function alphabeticalByLabel<T>(items: readonly T[], label: (item: T) => string): T[] {
  return [...items].sort((a, b) => compareCampusLabels(label(a), label(b)));
}

export function formatCampusList(names: readonly string[]): string {
  return [...names].map(shortCampusName).sort(compareCampusLabels).join(", ");
}
