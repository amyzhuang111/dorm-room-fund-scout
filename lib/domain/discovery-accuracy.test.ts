import assert from "node:assert/strict";
import { currentCalendarDay, daysSinceSignal, recencyOf, activeThisMonth, newThisYear, recordedOperatingStatus, statusOf, filterFacetCompanies } from "./sample-facets";
import { discoveryHref, safeDiscoveryReturn } from "./discovery-navigation";
import { browseHref, facetsFromSearchParams } from "./facet-url";

const today = { y: 2027, m: 1, d: 5 };
assert.deepEqual(currentCalendarDay(new Date("2027-01-01T02:00:00Z")), { y: 2026, m: 12, d: 31 });
assert.equal(recencyOf("2026-12-20", today), "month");
assert.equal(recencyOf("2026-12-00", today), "older");
assert.equal(recencyOf("2027-01-00", today), "year");
assert.equal(recencyOf("2027-00-00", today), "year");
assert.equal(recencyOf("2027-01-06", today), "future");
assert.equal(recencyOf("2028-00-00", today), "future");
assert.equal(recencyOf("2026-02-30", today), "none");
assert.equal(recencyOf("2027-13-01", today), "none");
assert.equal(recencyOf("2027-00-01", today), "none");
assert.equal(recencyOf("not a date", today), "none");
assert.equal(daysSinceSignal("2026-02-30", today), null);
assert.equal(activeThisMonth("2027-01-06", today), false);
assert.equal(activeThisMonth("2026-12-06", today), true);
assert.equal(activeThisMonth("2026-12-05", today), false);
assert.equal(newThisYear(2027, today), true);
assert.equal(newThisYear(2026, today), false);
const base = { id: "a", name: "Alpha", schoolId: "mit", signals: 2, signalKind: "acquisition" };
assert.equal(statusOf(base), "unknown");
assert.equal(statusOf({ ...base, operatingStatus: recordedOperatingStatus(" Active ") }), "active");
assert.equal(statusOf({ ...base, operatingStatus: recordedOperatingStatus("public") }), "active");
assert.equal(statusOf({ ...base, operatingStatus: recordedOperatingStatus("closed") }), "closed");
assert.equal(recordedOperatingStatus("possibly active"), null);
assert.equal(filterFacetCompanies([base], { status: "active" }).length, 0);
assert.equal(filterFacetCompanies([base], { status: "unknown" }).length, 1);
const params = new URLSearchParams("campus=mit&stage=Seed&status=unknown&recency=future&sort=name&c=a&more=3&feed=leaderboard");
const map = discoveryHref("map", params);
assert.ok(map.startsWith("/?"));
assert.ok(!map.includes("feed="));
const list = discoveryHref("companies", new URL(map, "http://local").searchParams);
assert.deepEqual(facetsFromSearchParams(new URL(list, "http://local").searchParams), facetsFromSearchParams(params));
assert.ok(list.includes("c=a"));
assert.ok(discoveryHref("signals", params).includes("feed=leaderboard"));
assert.equal(safeDiscoveryReturn(list, null), list);
assert.equal(safeDiscoveryReturn("https://evil.example", null), "/companies");
assert.equal(safeDiscoveryReturn("//evil.example", null), "/companies");
assert.equal(safeDiscoveryReturn("map", "mit"), "/?campus=mit");
const url = browseHref({ facets: facetsFromSearchParams(params), sort: "name", more: 3, c: "a" });
assert.ok(url.includes("status=unknown") && url.includes("recency=future") && url.includes("more=3"));
console.log("discovery accuracy and navigation tests passed");
